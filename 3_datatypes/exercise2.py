age = 20
print(type(age))
age = "Twenty"
print(type(age))

# in python varibles are dynamically typed, which means that you can change the type of a variable by assigning a new value to it. In this example, the variable `age` is first assigned an integer value of 20, and then it is reassigned a string value of "Twenty". The `type()` function is used to check the type of the variable at each stage.